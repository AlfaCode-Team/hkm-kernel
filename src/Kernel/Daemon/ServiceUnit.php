<?php

declare(strict_types=1);

namespace AlfacodeTeam\PhpServicePlatform\Kernel\Daemon;

/**
 * The systemd unit or launchd plist that supervises a provisioned daemon.
 *
 * GENERATED AND WRITTEN INTO THE PROJECT. NEVER INSTALLED.
 * -------------------------------------------------------
 * Installing a unit means a process that accepts network connections starts at
 * boot, as a chosen user, for ever. That is a decision an operator makes with
 * `sudo`, having read the file — not something a provisioning step does on the
 * way past. So this renders the text and {@see DaemonInstallCommand} prints the
 * two commands that would install it.
 *
 * The same reasoning, and the same shape, as `hkm service` for the queue
 * worker.
 *
 * WHAT A HAND-WRITTEN UNIT USUALLY GETS WRONG
 * -------------------------------------------
 * These are the settings that are absent from almost every unit written in a
 * hurry, and each one is a real incident:
 *
 * **`Restart=always` with a backoff.** Without `RestartSec` a crash-looping
 * daemon is restarted as fast as the kernel can fork it, which turns one bad
 * config into a busy CPU and a log file that fills the disk.
 *
 * **`ExecReload` using the daemon's own reload signal.** NATS, like most of
 * these, re-reads its config on SIGHUP and keeps every connection open.
 * Without this line a config change means a stop and a start, which drops every
 * subscriber — and on a bus that is at-most-once, every message in flight.
 *
 * **`LimitNOFILE`.** A bus holds one file descriptor per client. The default
 * soft limit is 1024 on most systems, so the 1025th connection is refused with
 * "too many open files" — at which point the application looks broken and the
 * daemon looks healthy.
 *
 * **Filesystem confinement.** `ProtectSystem=strict` plus a single
 * `ReadWritePaths` means a compromised daemon cannot write outside its own
 * directory. It costs one line and it is the difference between a bad day and a
 * very bad one.
 *
 * **`KeepAlive` on launchd is not the same as `Restart=always`.** launchd
 * restarts on ANY exit including a clean one, so a daemon told to stop comes
 * straight back. `SuccessfulExit=false` is what makes it restart on failure
 * only, and leaving it out is why "I stopped it and it keeps coming back".
 */
final class ServiceUnit
{
    /** Render the unit for whichever supervisor this platform uses. */
    public static function render(DaemonResult $result, string $user = ''): string
    {
        return $result->platform->supervisor() === 'launchd'
            ? self::launchd($result)
            : self::systemd($result, $user);
    }

    public static function label(DaemonResult $result): string
    {
        return 'hkm-' . $result->spec->name;
    }

    private static function systemd(DaemonResult $result, string $user): string
    {
        $spec   = $result->spec;
        $paths  = $result->paths;
        $argv   = $result->commandLine();
        $label  = self::label($result);
        $reload = $spec->reload === []
            ? ''
            : 'ExecReload=' . implode(' ', array_merge(
                [$paths->binary],
                ConfigRenderer::renderArgv($spec->reload, $result->tokens, 'daemon.service.reload'),
            )) . "\n";

        $account = $user !== ''
            ? "User={$user}\n"
            : "# User=hkm          # set this: running a network daemon as root is not necessary\n";

        return <<<UNIT
            # {$label}.service — generated by `hkm cli daemon:install {$spec->name}`
            #
            # {$spec->why}
            #
            # Install:
            #   sudo cp {$paths->serviceFile} /etc/systemd/system/{$label}.service
            #   sudo systemctl daemon-reload && sudo systemctl enable --now {$label}
            #
            # Reload after editing {$spec->configName} (keeps connections open):
            #   sudo systemctl reload {$label}

            [Unit]
            Description={$spec->name} {$spec->version} for {$result->tokens['project']}
            After=network-online.target
            Wants=network-online.target

            [Service]
            Type=simple
            {$account}WorkingDirectory={$paths->dir}
            ExecStart={$argv}
            {$reload}Restart=always
            # Without a backoff a crash-looping daemon is restarted as fast as
            # the system can fork it.
            RestartSec=2s
            # A bus holds one descriptor per client; the usual 1024 soft limit
            # refuses the 1025th connection as "too many open files".
            LimitNOFILE=65536
            # SIGTERM, then a real grace period — long enough to finish
            # flushing, short enough that a deploy is not held up.
            KillSignal=SIGTERM
            TimeoutStopSec=30s

            # Confinement. Costs one line each; a compromised daemon cannot
            # write outside its own directory.
            NoNewPrivileges=true
            PrivateTmp=true
            ProtectSystem=strict
            ProtectHome=true
            ReadWritePaths={$paths->dir}

            [Install]
            WantedBy=multi-user.target
            UNIT;
    }

    private static function launchd(DaemonResult $result): string
    {
        $spec  = $result->spec;
        $paths = $result->paths;
        $label = self::label($result);

        $arguments = '';

        foreach ($result->command() as $part) {
            $arguments .= '        <string>' . self::xml($part) . "</string>\n";
        }

        return <<<PLIST
            <?xml version="1.0" encoding="UTF-8"?>
            <!--
              {$label}.plist — generated by `hkm cli daemon:install {$spec->name}`

              {$spec->why}

              Install (per-user, no sudo):
                cp {$paths->serviceFile} ~/Library/LaunchAgents/{$label}.plist
                launchctl bootstrap gui/\$(id -u) ~/Library/LaunchAgents/{$label}.plist

              Stop and remove:
                launchctl bootout gui/\$(id -u)/{$label}
            -->
            <!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
            <plist version="1.0">
            <dict>
                <key>Label</key>
                <string>{$label}</string>

                <key>ProgramArguments</key>
                <array>
            {$arguments}    </array>

                <key>WorkingDirectory</key>
                <string>{$paths->dir}</string>

                <!--
                  KeepAlive as a DICTIONARY, not <true/>. A bare true restarts
                  the job on ANY exit including a clean one, so a daemon you
                  stopped comes straight back and looks unkillable.
                -->
                <key>KeepAlive</key>
                <dict>
                    <key>SuccessfulExit</key>
                    <false/>
                </dict>

                <key>RunAtLoad</key>
                <true/>

                <key>StandardOutPath</key>
                <string>{$paths->logFile}</string>
                <key>StandardErrorPath</key>
                <string>{$paths->logFile}</string>

                <key>SoftResourceLimits</key>
                <dict>
                    <key>NumberOfFiles</key>
                    <integer>65536</integer>
                </dict>
            </dict>
            </plist>
            PLIST;
    }

    private static function xml(string $value): string
    {
        return htmlspecialchars($value, ENT_XML1 | ENT_QUOTES, 'UTF-8');
    }
}
